#!/usr/bin/env python3
"""Rebuild the fonts used by the server-side conversation PDF export (supabase/functions/_shared/pdf).

Requires fonttools. Inputs (both SIL OFL 1.1):
  NOTO_SANS_VF  = Noto Sans variable font (NotoSans[wdth,wght].ttf, google/fonts ofl/notosans)
  NOTO_EMOJI_VF = Noto Emoji variable font (NotoEmoji[wght].ttf, google/fonts ofl/notoemoji)

jsPDF 2.x only handles BMP code points, so every astral emoji in Noto Emoji is
also mapped to a Private Use Area code point (U+E000 + index, ascending code
point order). emojiPua.ts lists the astral code points as [start, count]
runs (emojiPua.ts) so layout.ts can rebuild the same mapping. The TTFs are
written as base64 TS modules (font-*.ts) so the Edge bundle needs no file reads.
Usage: build-pdf-fonts.py NOTO_SANS_VF NOTO_EMOJI_VF OUT_DIR
"""
import base64, json, sys, os
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset
from fontTools.ttLib.tables._c_m_a_p import cmap_format_4

sans_vf, emoji_vf, out = sys.argv[1:4]
LATIN = "U+0000-024F,U+0259,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0300-036F,U+0370-03FF,U+0400-04FF,U+1E00-1EFF,U+2000-206F,U+20A0-20CF,U+2100-214F,U+2190-21FF,U+2212,U+2215,U+25A1,U+FFFD"

def sub(font, unicodes):
    opts = subset.Options(); opts.layout_features = []; opts.hinting = False; opts.desubroutinize = True
    opts.name_IDs = ["*"]; opts.notdef_outline = True
    s = subset.Subsetter(opts); s.populate(unicodes=unicodes); s.subset(font)

for wght, name in ((400, "NotoSans-Regular.ttf"), (700, "NotoSans-Bold.ttf")):
    f = instancer.instantiateVariableFont(TTFont(sans_vf), {"wght": wght, "wdth": 100})
    sub(f, subset.parse_unicodes(LATIN)); f.save(os.path.join(out, name))

f = instancer.instantiateVariableFont(TTFont(emoji_vf), {"wght": 400})
best = f.getBestCmap()
astral = sorted(cp for cp in best if cp > 0xFFFF)
assert len(astral) <= 0x1900, "PUA overflow"
emoji_cps = [cp for cp in best if cp > 0x7F]
sub(f, emoji_cps)
best = f.getBestCmap()
bmp = {cp: g for cp, g in best.items() if cp <= 0xFFFF and not (0xE000 <= cp <= 0xF8FF)}
for i, cp in enumerate(astral):
    if cp in best: bmp[0xE000 + i] = best[cp]
t = cmap_format_4(4); t.platformID, t.platEncID, t.language, t.cmap = 3, 1, 0, bmp
f["cmap"].tables = [t]
f.save(os.path.join(out, "NotoEmoji-Regular-pua.ttf"))
runs = []
for cp in astral:
    if runs and runs[-1][0] + runs[-1][1] == cp: runs[-1][1] += 1
    else: runs.append([cp, 1])
open(os.path.join(out, "emojiPua.ts"), "w").write(
    "// Generated by scripts/build-pdf-fonts.py – astral emoji code points in NotoEmoji-Regular-pua.ttf as [start, count] runs.\n"
    "// Glyph i (ascending code point order) is also mapped to U+E000 + i, because jsPDF only handles BMP code points.\n"
    "export const EMOJI_PUA_RUNS: [number, number][] = " + json.dumps(runs, separators=(",", ":")) + ";\n")
for ttf, const in [("NotoSans-Regular.ttf", "NOTO_SANS_REGULAR"), ("NotoSans-Bold.ttf", "NOTO_SANS_BOLD"), ("NotoEmoji-Regular-pua.ttf", "NOTO_EMOJI_PUA")]:
    data = open(os.path.join(out, ttf), "rb").read(); os.remove(os.path.join(out, ttf))
    open(os.path.join(out, "font-" + ttf[:-4] + ".ts"), "w").write(
        f"// Generated by scripts/build-pdf-fonts.py from {ttf} (SIL OFL 1.1, see OFL.txt). Base64 TTF.\n"
        f"export const {const} = \"{base64.b64encode(data).decode()}\";\n")
print(len(astral), "astral emoji;", len(runs), "runs")
